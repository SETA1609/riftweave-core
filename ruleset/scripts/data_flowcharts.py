#!/usr/bin/env python3
"""Draw the data as Mermaid flowcharts (docs/core/data-model.md, M5-63): the perk ladders from
features/core.json and every formula tree in ruleset/data. M5-57's data_model_diagram.py draws
the schemas; this draws the rows. Nothing is drawn by hand, so test_data_flowcharts.py fails
until the pages are rewritten.

Run with:
    python ruleset/scripts/data_flowcharts.py           print both pages
    python ruleset/scripts/data_flowcharts.py --write   rewrite docs/core/perk-ladders.md and formula-trees.md
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
DATA = ROOT / "ruleset" / "data"
LADDERS_PAGE = ROOT / "docs" / "core" / "perk-ladders.md"
FORMULAS_PAGE = ROOT / "docs" / "core" / "formula-trees.md"
# The pages' Modified line (M5-53): bump it with the data change that changes a chart.
MODIFIED = "2026-11-17"
FEATURE_PREFIX = "core:feature/"
SYMBOLS = {"add": "+", "subtract": "−", "multiply": "×", "divide": "÷ (floor)"}


def node_id(text):
    return re.sub(r"[^a-zA-Z0-9_]", "_", text)


def quote(text):
    """A Mermaid label: double quotes become #quot;."""
    return '"' + str(text).replace('"', "#quot;") + '"'


# --- perk ladders --------------------------------------------------------------------------

def perks():
    return [row for row in json.loads((DATA / "features" / "core.json").read_text())["features"] if row["type"] == "perk"]


def held(entry):
    """A prerequisite perk's key and rank: a bare ref is rank 1."""
    if isinstance(entry, str):
        return entry.removeprefix(FEATURE_PREFIX), 1
    return entry["perk"].removeprefix(FEATURE_PREFIX), entry.get("rank", 1)


def gates(perk):
    """The perk's level, skill, and attribute gates, as one short line."""
    need = perk.get("prerequisite", {})
    parts = [f"Lv {need['level']}"] if "level" in need else []
    for skill in need.get("skills", []):
        ids = skill["id"] if isinstance(skill["id"], list) else [skill["id"]]
        parts.append(" or ".join(ref.rsplit("/", 1)[-1] for ref in ids) + f" {skill['min']}")
    parts += [f"{ability.upper()} {value}" for ability, value in need.get("abilities", {}).items()]
    return " · ".join(parts)


def perk_label(perk):
    ranks = f" (ranks {perk['ranks']})" if perk.get("ranks", 1) > 1 else ""
    line = gates(perk)
    return quote(perk["label"] + ranks + (f"<br/>{line}" if line else ""))


def ladder_chart(category, rows, by_key):
    """One graph LR for a category: its perks, the prerequisite perks they name, and the edges."""
    out = ["```mermaid", "graph LR"]
    drawn = set()
    for perk in rows:
        out.append(f"  {node_id(perk['key'])}[{perk_label(perk)}]")
        drawn.add(perk["key"])
    for perk in rows:
        for entry in perk.get("prerequisite", {}).get("perks", []):
            key, rank = held(entry)
            if key not in drawn:
                other = by_key.get(key, {"label": key})
                out.append(f"  {node_id(key)}([{quote(other['label'] + '<br/>' + other.get('category', 'other'))}])")
                drawn.add(key)
            arrow = f" -- rank {rank} --> " if rank > 1 else " --> "
            out.append(f"  {node_id(key)}{arrow}{node_id(perk['key'])}")
    out.append("```")
    return "\n".join(out)


def ladders_page():
    rows = perks()
    by_key = {perk["key"]: perk for perk in rows}
    needed = {held(entry)[0] for perk in rows for entry in perk.get("prerequisite", {}).get("perks", [])}
    linked = [perk for perk in rows if perk.get("prerequisite", {}).get("perks") or perk["key"] in needed]
    loose = [perk for perk in rows if perk not in linked]
    categories = sorted({perk.get("category", "other") for perk in linked})
    out = [
        "# Perk ladders", "", f"Modified: {MODIFIED}", "",
        "Generated by `ruleset/scripts/data_flowcharts.py` from `ruleset/data/features/core.json`; do not",
        "edit by hand. Run `python ruleset/scripts/data_flowcharts.py --write` after a perk change, and",
        "`test_data_flowcharts.py` fails until the page matches.", "",
        "One chart per perk `category`. A box is a perk with its gates (level, skills, attributes); an",
        "arrow runs from a prerequisite perk to the perk that needs it, labelled with the rank it needs",
        "when more than 1. A rounded box is a prerequisite from another category. A ladder that stops",
        "early, or a perk nothing leads to, shows at a glance.", "",
        f"{len(rows)} perks: {len(linked)} on a ladder, {len(loose)} with no perk before or after them.",
    ]
    for category in categories:
        members = [perk for perk in linked if perk.get("category", "other") == category]
        out += ["", f"## {category.capitalize()}", "", ladder_chart(category, members, by_key)]
    out += ["", "## Perks on no ladder", "", "No perk is required before them and none needs them; their gates are skills,",
            "attributes, and level only.", "", "| Perk | Category | Gates |", "| --- | --- | --- |"]
    out += [f"| {perk['label']} | {perk.get('category', 'other')} | {gates(perk) or '—'} |" for perk in loose]
    return "\n".join(out) + "\n"


# --- formula trees -------------------------------------------------------------------------

def is_tree(node):
    return isinstance(node, dict) and "operation" in node and "arguments" in node


def trees(node, path=()):
    """Every formula tree in a JSON value: (path, tree), outermost only."""
    if is_tree(node):
        yield path, node
        return
    if isinstance(node, dict):
        for key, value in node.items():
            yield from trees(value, path + (key,))
    elif isinstance(node, list):
        for index, value in enumerate(node):
            yield from trees(value, path + (str(index),))


def all_trees():
    for file in sorted(DATA.rglob("*.json")):
        if "bases" in file.parts:
            continue
        for path, tree in trees(json.loads(file.read_text())):
            yield file.relative_to(DATA).as_posix(), ".".join(path), tree


def tree_chart(tree):
    out = ["```mermaid", "flowchart TB"]
    counter = [0]

    def draw(node):
        counter[0] += 1
        name = f"n{counter[0]}"
        if is_tree(node):
            out.append(f"  {name}{{{quote(SYMBOLS.get(node['operation'], node['operation']))}}}")
            for argument in node["arguments"]:
                out.append(f"  {name} --> {draw(argument)}")
        elif "literal" in node:
            out.append(f"  {name}[{quote(node['literal'])}]")
        elif "attribute" in node:
            out.append(f"  {name}([{quote(node['attribute'].upper())}])")
        elif "variable" in node:
            out.append(f"  {name}([{quote(node['variable'])}])")
        else:
            out.append(f"  {name}[{quote(json.dumps(node))}]")
        return name

    draw(tree)
    out.append("```")
    return "\n".join(out)


def formulas_page():
    found = list(all_trees())
    out = [
        "# Formula trees", "", f"Modified: {MODIFIED}", "",
        "Generated by `ruleset/scripts/data_flowcharts.py` from every formula tree in `ruleset/data/`;",
        "do not edit by hand. Run `python ruleset/scripts/data_flowcharts.py --write` after a formula",
        "change, and `test_data_flowcharts.py` fails until the page matches. The tree format is in",
        "[formula.md](formula.md).", "",
        "A diamond is an operation, read top to bottom: its arguments hang under it, left to right",
        "(`−` subtracts the later ones from the first, `÷` divides and rounds down). A rounded box is",
        "an input (an attribute in capitals, or a variable the caller passes); a square box is a number.", "",
        f"{len(found)} formula trees.",
    ]
    current = None
    for file, path, tree in found:
        if file != current:
            out += ["", f"## `{file}`"]
            current = file
        out += ["", f"### `{path or '(the file)'}`", "", tree_chart(tree)]
    return "\n".join(out) + "\n"


def main(argv):
    pages = {LADDERS_PAGE: ladders_page(), FORMULAS_PAGE: formulas_page()}
    if argv[1:] == ["--write"]:
        for page, text in pages.items():
            page.write_text(text)
            print(f"wrote {page.relative_to(ROOT)}")
    else:
        sys.stdout.write("".join(pages.values()))


if __name__ == "__main__":
    main(sys.argv)
